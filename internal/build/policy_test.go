func TestBuildSourcePolicy(t *testing.T) {
	const dockerfile = "# syntax=registry.example.com/images/dockerfile:1\n" +
		"ARG GO_VERSION\n" +
		"FROM registry.example.com/images/golang:${GO_VERSION} AS build\n" +
		"FROM gcr.io/distroless/static\n" +
		"COPY --from=build /out /out\n"
	tests := []struct {
		name       string
		mode       spec.PolicyMode
		dockerfile string
		wantErr    string
		wantWarn   string
	}{
		{name: "permitted", dockerfile: "FROM registry.example.com/images/base:v1\n"},
		{name: "rejected base fails before buildx", dockerfile: dockerfile,
			wantErr: "Dockerfile.controller:4 (FROM): source policy: image gcr.io/distroless/static"},
		{name: "warn mode builds and narrates", mode: spec.PolicyWarn, dockerfile: dockerfile,
			wantWarn: "gcr.io/distroless/static"},
		{name: "unresolvable reference is rejected", dockerfile: "ARG BASE\nFROM ${BASE}/app:v1\n",
			wantErr: "cannot be resolved"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := newWorld(t)
			w.write("Dockerfile.controller", tt.dockerfile)
			w.global.Policy = spec.SourcePolicy{Layers: []spec.PolicyLayer{(&spec.BuildPolicy{
				Mode:   tt.mode,
				Images: spec.PolicyRules{Allow: []string{"registry.example.com/images/**"}},
			}).Layer("test config")}}
			var warns []string
			e := w.engine()
			e.onEvent = func(ev Event) {
				if ev.Kind == "warn" {
					warns = append(warns, ev.Message)
				}
			}
			_, err := e.Build(context.Background(), "controller", Options{DryRun: true})
			switch {
			case tt.wantErr == "" && err != nil:
				t.Fatalf("Build: %v", err)
			case tt.wantErr != "":
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("Build = %v, want %q", err, tt.wantErr)
				}
				if len(w.builder.calls) != 0 {
					t.Errorf("buildx ran %d time(s) despite the rejection", len(w.builder.calls))
				}
				return
			}
			if len(w.builder.calls) != 1 {
				t.Errorf("buildx calls = %d, want 1", len(w.builder.calls))
			}
			if tt.wantWarn == "" && len(warns) != 0 || tt.wantWarn != "" &&
				(len(warns) != 1 || !strings.Contains(warns[0], tt.wantWarn)) {
				t.Errorf("warnings = %q, want one mentioning %q", warns, tt.wantWarn)
			}
		})
	}
}

// TestBuildWithoutImagePolicySkipsTheDockerfile: no image policy, no read —
// a build whose Dockerfile is generated by an earlier buildx stage or is
// otherwise absent is not this check's business.
func TestBuildWithoutImagePolicySkipsTheDockerfile(t *testing.T) {
	w := newWorld(t)
	if _, err := w.engine().Build(context.Background(), "controller", Options{DryRun: true}); err != nil {
		t.Fatalf("Build without a Dockerfile on disk: %v", err)
	}
}
