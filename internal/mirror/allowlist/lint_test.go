func TestLint(t *testing.T) {
	a := &spec.Allowlist{Vulnerabilities: []spec.AllowlistEntry{
		{Statement: "no id", ExpiredAt: "2026-09-01"},
		{ID: "CVE-1", ExpiredAt: "2026-09-01"},
		{ID: "CVE-2", Statement: "s"},
		{ID: "CVE-3", Statement: "s", ExpiredAt: "soon"},
		{ID: "CVE-4", Statement: "s", ExpiredAt: "2026-08-11"}, // today: lapsed
		{ID: "CVE-5", Statement: "s", ExpiredAt: "2026-10-01"}, // within 60d
		{ID: "CVE-6", Statement: "s", ExpiredAt: "2026-12-01"}, // beyond 60d
	}}
	issues := Lint(a, today, 60)
	got := make([]string, 0, len(issues))
	var expired []string
	for _, i := range issues {
		got = append(got, i.String())
		if i.Expired {
			expired = append(expired, i.ID)
		}
	}
	want := []string{
		"allowlist entry 0 missing id",
		"allowlist CVE-1 missing statement",
		"allowlist CVE-2 missing expired_at",
		`allowlist CVE-3 has unparseable expired_at "soon"`,
		"allowlist CVE-4 expired on 2026-08-11 — re-review required",
		"allowlist CVE-6 expires more than 60 days out",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Lint =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if !reflect.DeepEqual(expired, []string{"CVE-4"}) {
		t.Errorf("expired issues = %v, want only CVE-4", expired)
	}
	if Lint(nil, today, 90) != nil {
		t.Error("a missing allowlist has issues")
	}
}

func TestActive(t *testing.T) {
	a := &spec.Allowlist{Vulnerabilities: []spec.AllowlistEntry{
		{ID: "LIVE", ExpiredAt: "2026-09-01"},
		{ID: "LAPSED", ExpiredAt: "2026-08-11"},
		{ID: "MALFORMED", ExpiredAt: "soon"},
		{ID: "MISSING"},
	}}
	got := Active(a, today)
	if len(got.Vulnerabilities) != 1 || got.Vulnerabilities[0].ID != "LIVE" {
		t.Errorf("Active = %+v, want only LIVE", got.Vulnerabilities)
	}
	if len(Active(nil, today).Vulnerabilities) != 0 {
		t.Error("Active(nil) is not empty")
	}
}

func TestRegenerate(t *testing.T) {
	path := filepath.Join(t.TempDir(), "security", "allowlists", "controller.yaml")
	prev := &spec.Allowlist{Vulnerabilities: []spec.AllowlistEntry{
		{ID: "CVE-OLD", Statement: "s", ExpiredAt: "2026-09-01"},
	}}
	rows := []Finding{{ID: "CVE-NEW", Package: "libfoo", Installed: "1.0.0", FixedIn: []string{"1.0.1"}}}
	stats, err := Regenerate(path, BuildBanner, rows, prev, today, 30, "Built from main.")
	if err != nil {
		t.Fatalf("Regenerate: %v", err)
	}
	if stats.Added != 1 || !reflect.DeepEqual(stats.Dropped, []string{"CVE-OLD"}) {
		t.Errorf("stats = %+v", stats)
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"# GENERATED by patchy build",
		"`patchy build --update-allowlists`",
		"# Built from main.",
		"  - id: CVE-NEW",
		`expired_at: "2026-09-10"`, // today + 30d
	} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("regenerated file lacks %q:\n%s", want, raw)
		}
	}
	got, err := spec.LoadAllowlistFile(path)
	if err != nil || len(got.Vulnerabilities) != 1 {
		t.Fatalf("LoadAllowlistFile = %+v, %v", got, err)
	}
	// A missing file loads as empty, so a first --update-allowlists run
	// needs no seed.
	empty, err := spec.LoadAllowlistFile(filepath.Join(t.TempDir(), "absent.yaml"))
	if err != nil || len(empty.Vulnerabilities) != 0 {
		t.Errorf("missing file = %+v, %v", empty, err)
	}
}
