package allowlist

import (
	"fmt"
	"strings"

	"go.yaml.in/yaml/v4"

	"github.com/bitwise-media-group/patchy/internal/mirror/spec"
)

// Banner is the GENERATED comment block atop a rendered allowlist: who
// regenerates the file, from what, and where its whole-file context lives.
type Banner string

// The two generators' banners. MirrorBanner is byte-for-byte the text every
// committed mirror allowlist already carries, so regeneration never churns it.
const (
	MirrorBanner Banner = "# GENERATED by patchy mirror — do not hand-edit the entries.\n" +
		"# Regenerated by `patchy mirror upgrade` from a fresh scan of the locked images:\n" +
		"# findings that no longer appear are dropped, surviving entries keep their\n" +
		"# original expired_at (renewed once it has lapsed), and per-entry notes are\n" +
		"# preserved. Whole-file context lives in scan.allowlist.preamble in\n" +
		"# manifest.yaml; per-finding analysis goes in a \"notes\" field on the entry.\n"
	BuildBanner Banner = "# GENERATED by patchy build — do not hand-edit the entries.\n" +
		"# Regenerated by `patchy build --update-allowlists` from a fresh scan of the built\n" +
		"# image: findings that no longer appear are dropped, surviving entries keep their\n" +
		"# original expired_at (renewed once it has lapsed), and per-entry notes are\n" +
		"# preserved. Whole-file context lives in the build entry's\n" +
		"# scan.allowlist.preamble; per-finding analysis goes in a \"notes\" field on the entry.\n"
)

// Render produces a mirror allowlist file under MirrorBanner.
func Render(entries []spec.AllowlistEntry, preamble string) []byte {
	return RenderBanner(MirrorBanner, entries, preamble)
}

// RenderBanner produces the generated allowlist file: the GENERATED banner,
// the entry's preamble as comments, then the entries. expired_at is always
// double-quoted, matching the hand-written allowlists' style so an entry
// opting in produces no gratuitous diff.
func RenderBanner(banner Banner, entries []spec.AllowlistEntry, preamble string) []byte {
	var b strings.Builder
	b.WriteString(string(banner))
	if preamble != "" {
		b.WriteString("#\n")
		for line := range strings.SplitSeq(strings.TrimRight(preamble, "\n"), "\n") {
			if line == "" {
				b.WriteString("#\n")
			} else {
				b.WriteString("# ")
				b.WriteString(line)
				b.WriteString("\n")
			}
		}
	}
	if len(entries) == 0 {
		b.WriteString("vulnerabilities: []\n")
		return []byte(b.String())
	}
	b.WriteString("vulnerabilities:\n")
	for _, e := range entries {
		writeField(&b, "  - ", "id", e.ID)
		writeField(&b, "    ", "statement", e.Statement)
		fmt.Fprintf(&b, "    expired_at: %q\n", e.ExpiredAt)
		if e.Notes != "" {
			writeField(&b, "    ", "notes", e.Notes)
		}
	}
	return []byte(b.String())
}

// writeField emits one key/value line, encoding the value the way a YAML
// encoder would (plain where safe, quoted or block otherwise).
func writeField(b *strings.Builder, prefix, key, value string) {
	enc := encodeScalar(value, prefix)
	fmt.Fprintf(b, "%s%s: %s\n", prefix, key, enc)
}

// encodeScalar renders value as a YAML scalar for an inline position at the
// given indentation. Single-line output splices after "key: "; multi-line
// values become an indented block scalar.
func encodeScalar(value, prefix string) string {
	raw, err := yaml.Marshal(value)
	if err != nil {
		// Marshal of a string cannot fail; quote defensively.
		return fmt.Sprintf("%q", value)
	}
	enc := strings.TrimRight(string(raw), "\n")
	if !strings.Contains(enc, "\n") {
		return enc
	}
	// Block scalar: re-base the encoder's fixed 4-space content indent to
	// two deeper than the key.
	indent := strings.Repeat(" ", len(prefix)+2)
	lines := strings.Split(enc, "\n")
	for i := 1; i < len(lines); i++ {
		lines[i] = indent + strings.TrimPrefix(lines[i], "    ")
	}
	return strings.Join(lines, "\n")
}
